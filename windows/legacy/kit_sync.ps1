# ============================================================================
#  kit_sync.ps1 - какие файлы набора надо отправить на ноутбук.
#
#  Зачем отдельным файлом: логику «что изменилось» надо ПРОВЕРЯТЬ, а не
#  надеяться на неё. Функция чистая (никакого ssh внутри), поэтому её можно
#  вызвать в тесте и получить ответ без сети и без карты.
#
#  Правило простое: файл отправляется, если его нет на ноутбуке или если md5
#  отличается. Пустой/битый список с ноутбука (например, там нет md5sum или
#  папки) означает «состояние неизвестно» - тогда отправляются все файлы:
#  молча пропустить файл дороже, чем скопировать лишний.
# ============================================================================

function Compare-KitFiles {
  <#
    .SYNOPSIS
      Список файлов, которые надо отправить.
    .PARAMETER Local
      Хэш-таблица имя -> md5 (нижний регистр) для файлов на этой машине.
    .PARAMETER Remote
      Хэш-таблица имя -> md5, прочитанная с ноутбука (может быть пустой).
  #>
  param(
    [hashtable]$Local = @{},
    [hashtable]$Remote = @{}
  )
  $send = @()
  foreach ($name in ($Local.Keys | Sort-Object)) {
    $mine = "$($Local[$name])".ToLower()
    if (-not $Remote.ContainsKey($name)) {
      $send += $name
      continue
    }
    $theirs = "$($Remote[$name])".ToLower()
    if ($theirs -ne $mine) { $send += $name }
  }
  return $send
}

function Read-Md5List {
  <#
    .SYNOPSIS
      Разобрать вывод "md5sum файл файл ..." в хэш-таблицу имя -> md5.
      Строки, которые не похожи на md5sum, пропускаются молча: на ноутбуке
      могло не быть части файлов, и это не ошибка, а повод отправить их.
  #>
  param([string[]]$Lines = @())
  $map = @{}
  foreach ($line in $Lines) {
    if ($line -match '^([0-9a-fA-F]{32})\s+\*?(\S+)$') {
      $map[$Matches[2]] = $Matches[1].ToLower()
    }
  }
  return $map
}
