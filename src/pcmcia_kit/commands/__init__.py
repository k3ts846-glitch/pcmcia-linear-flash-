"""Команды пульта: по модулю на команду.

Общая обвязка (подключение, синхронизация набора, отправка образа, показ
результата) вынесена в `pcmcia_kit.steps`. Модуль команды отвечает только на
вопрос «чем эта команда отличается от остальных».

    menu       меню на весь экран (вход по двойному щелчку)
    probe      info, chip, canwrite, diag — только чтение, карта не меняется
    read       снять образ и забрать к себе
    write      записать образ на карту (и проба записи без драйвера)
    erase      стереть карту
    verify     сверить файл с картой
    report     полный отчёт
    selftest   прогнать тесты набора на ноутбуке
    key        настроить вход по ключу
"""

__all__ = ["menu", "probe", "read", "write", "erase", "verify", "report",
           "selftest", "key"]
